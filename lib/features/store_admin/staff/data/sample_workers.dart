/// A worker with ordinary details: active and free.
Worker _extra(
  String id,
  String name,
  WorkerRole role, {
  String? branchId,
  bool isOnDuty = true,
}) {
  // Number from the id, used to make each phone number different.
  final number = int.parse(id.substring(1));

  return Worker(
    id: id,
    name: name,
    email: '${name.toLowerCase().replaceAll(' ', '.')}@grocerly.my',
    phone: '012-555 ${(200 + number).toString().padLeft(4, '0')}',
    role: role,
    branchId: branchId,
    isActive: true,
    isOnDuty: isOnDuty,
    ordersToday: const [],
    joinedAt: DateTime(2026, 1, number),
  );
}
